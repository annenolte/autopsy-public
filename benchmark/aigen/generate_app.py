"""Generate a small multi-file app with SONNET_MODEL from a NORMAL feature
request (no mention of vulnerabilities), to test Autopsy on genuinely
AI-generated code — the title claim ("AI-Generated Source Code").

The prompt asks only for a working feature; it does NOT ask for insecure code.
Whatever vulnerabilities appear are the model's own, and are labelled
conservatively afterwards in ground_truth_aigen.json by reading the output.

Output: benchmark/aigen/app/<files>  (+ a README marking it an unaudited fixture)

Run:  python benchmark/aigen/generate_app.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(_ROOT))
from dotenv import load_dotenv  # noqa: E402
load_dotenv(_ROOT / ".env")

from autopsy.llm.client import stream_sonnet, get_usage, reset_usage  # noqa: E402

APP_DIR = Path(__file__).resolve().parent / "app"

SYSTEM = (
    "You are a senior Python engineer. Produce clean, working, idiomatic Flask "
    "code. Output ONLY source files, each introduced by a line of the exact form "
    "'=== FILE: <relative/path> ===' followed by the file's contents. No prose, "
    "no markdown fences, no explanation."
)

REQUEST = (
    "Build a small Flask web app (keep it simple, a few files) with:\n"
    "1. User registration and login (username + password), with sessions.\n"
    "2. A profile page where a logged-in user can upload a profile photo.\n"
    "3. An admin page with a search box that looks users up by name.\n"
    "Use SQLite for storage. Split into a few modules (e.g. app.py, db.py, "
    "auth.py, admin.py). Make it runnable. Do not add comments explaining "
    "security; just write the app."
)


def parse_files(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    parts = re.split(r'(?m)^===\s*FILE:\s*(.+?)\s*===\s*$', text)
    # parts: [pre, name1, body1, name2, body2, ...]
    for i in range(1, len(parts), 2):
        name = parts[i].strip().lstrip("/")
        body = parts[i + 1]
        # strip leading/trailing blank lines and any stray ``` fences
        body = re.sub(r'^\s*```[a-zA-Z]*\n', '', body)
        body = re.sub(r'\n```\s*$', '\n', body)
        out[name] = body.lstrip("\n")
    return out


def main():
    reset_usage()
    chunks = []
    for c in stream_sonnet(SYSTEM, REQUEST, max_tokens=8192):
        chunks.append(c)
    text = "".join(chunks)
    files = parse_files(text)
    if not files:
        print("No files parsed. Raw head:\n", text[:800])
        sys.exit(1)
    APP_DIR.mkdir(parents=True, exist_ok=True)
    for name, body in files.items():
        # keep it flat & safe: no path escapes
        safe = Path(name).name if (".." in name or name.startswith("/")) else name
        dest = APP_DIR / safe
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(body)
        print(f"wrote {dest}  ({len(body.splitlines())} lines)")
    (APP_DIR / "README.md").write_text(
        "# AI-generated test fixture (UNAUDITED)\n\n"
        "Generated by `benchmark/aigen/generate_app.py` with "
        "`claude-sonnet-4-5-20250929` from a normal feature request (login, "
        "profile photo upload, admin search) that did NOT ask for insecure code. "
        "Any vulnerabilities are the model's own. **Do not deploy.** Used only as "
        "a held-out target to test Autopsy on genuinely AI-generated code; "
        "vulnerabilities are labelled conservatively in "
        "`benchmark/aigen/ground_truth_aigen.json`.\n")
    u = get_usage()
    print("usage:", u)


if __name__ == "__main__":
    main()
